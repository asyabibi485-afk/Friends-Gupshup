-- Friend Gup Shup — DIRECT CHAT, SAFE TO RUN AGAIN
--
-- Flow:
--   1) Create profile with username
--   2) Search friend's username
--   3) Tap Chat
--   4) Chat opens immediately
--
-- There are NO friend requests, accept/decline buttons, or friend codes.
--
-- IMPORTANT: this version uses the simple unauthenticated Streamlit client.
-- RLS is disabled so the app can read/write these demo tables.
-- Do not use this database configuration for sensitive/private production data.

create table if not exists public.users (
  id bigint generated by default as identity primary key,
  friend_id text unique not null,
  name text not null,
  username text,
  created_at timestamptz default now()
);

create table if not exists public.friendships (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(id) on delete cascade,
  friend_id bigint not null references public.users(id) on delete cascade,
  created_at timestamptz default now(),
  unique(user_id, friend_id)
);

create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  sender_id text not null,
  receiver_id text not null,
  message text not null,
  created_at timestamptz default now()
);

-- Compatibility with older installations.
alter table public.users add column if not exists friend_id text;
alter table public.users add column if not exists name text;
alter table public.users add column if not exists username text;
alter table public.users add column if not exists created_at timestamptz default now();

-- Old rows need a usable friend_id before the NOT NULL/unique constraint is used.
update public.users
set friend_id = upper(substr(md5(random()::text || clock_timestamp()::text || id::text), 1, 8))
where friend_id is null or trim(friend_id) = '';

-- Old rows need a usable name.
update public.users
set name = 'Friend'
where name is null or trim(name) = '';

-- Create usernames for old rows.
update public.users
set username = lower(
  regexp_replace(left(coalesce(name, 'friend'), 16), '[^a-zA-Z0-9_]', '', 'g')
) || id::text
where username is null or trim(username) = '';

-- Make existing duplicate usernames unique before creating the unique index.
with duplicates as (
  select id, username,
         row_number() over (partition by lower(username) order by id) as rn
  from public.users
  where username is not null and trim(username) <> ''
)
update public.users u
set username = left(regexp_replace(lower(d.username), '[^a-z0-9_]', '', 'g'), 16)
               || case when d.rn = 1 then '' else d.rn::text end
               || u.id::text
from duplicates d
where u.id = d.id and d.rn > 1;

-- Ensure required user columns are constrained after old data is repaired.
alter table public.users alter column friend_id set not null;
alter table public.users alter column name set not null;

-- Disable RLS for this simple no-login version.
alter table public.users disable row level security;
alter table public.friendships disable row level security;
alter table public.messages disable row level security;

-- Remove old policies. DROP IF EXISTS is safe if they are already gone.
drop policy if exists users_select on public.users;
drop policy if exists users_insert on public.users;
drop policy if exists users_update on public.users;
drop policy if exists users_delete on public.users;
drop policy if exists friendships_select on public.friendships;
drop policy if exists friendships_insert on public.friendships;
drop policy if exists friendships_update on public.friendships;
drop policy if exists friendships_delete on public.friendships;
drop policy if exists messages_select on public.messages;
drop policy if exists messages_insert on public.messages;
drop policy if exists messages_update on public.messages;
drop policy if exists messages_delete on public.messages;

-- Indexes used by username search, connections, and chat loading.
drop index if exists public.users_username_unique;
create unique index users_username_unique
  on public.users (lower(username));

create index if not exists users_username_search_idx
  on public.users (lower(username));
create index if not exists friendships_user_idx
  on public.friendships (user_id);
create index if not exists friendships_friend_idx
  on public.friendships (friend_id);
create index if not exists messages_chat_idx
  on public.messages (sender_id, receiver_id, created_at);

-- Make sure the browser-facing Supabase role can use these tables.
grant usage on schema public to anon, authenticated;
grant select, insert, update, delete on public.users to anon, authenticated;
grant select, insert, update, delete on public.friendships to anon, authenticated;
grant select, insert, update, delete on public.messages to anon, authenticated;
grant usage, select on all sequences in schema public to anon, authenticated;

-- Add messages to Realtime only if it is not already enabled.
do $$
begin
  if not exists (
    select 1
    from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'messages'
  ) then
    alter publication supabase_realtime add table public.messages;
  end if;
exception when undefined_object then
  -- Realtime publication is unavailable; chat still works by polling.
  null;
end $$;

-- Verification: all three should show rowsecurity = false.
select schemaname, tablename, rowsecurity
from pg_tables
where schemaname = 'public'
  and tablename in ('users', 'friendships', 'messages')
order by tablename;
